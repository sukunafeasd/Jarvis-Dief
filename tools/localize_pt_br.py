def migrate(path):
    source = path.read_text(encoding="utf-8")
    tokens = []
    count = 0
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        value = token.string
        if token.type == tokenize.STRING:
            try:
                literal = ast.literal_eval(value)
            except (ValueError, SyntaxError):
                literal = None
            if isinstance(literal, str) and literal in TEXT:
                value = repr(TEXT[literal])
        elif token.type == tokenize.FSTRING_MIDDLE and value in TEXT:
            value = TEXT[value]
        if value != token.string:
            count += 1
        tokens.append(token._replace(string=value))
    result = tokenize.untokenize(tokens)
    ast.parse(result)
    if count:
        path.write_text(result, encoding="utf-8")
    return count


